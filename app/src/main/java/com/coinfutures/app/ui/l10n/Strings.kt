    open fun nextBreakout(long: Boolean, price: String, vol: String?) =
        "1H candle must close ${if (long) "at or above" else "at or below"} $price" + (vol?.let { " with volume ≥ $it" } ?: "")
    open fun nextRetest(long: Boolean, edge: String, n: Int?) =
        "A 15M candle must touch the zone and close ${if (long) "at or above" else "at or below"} $edge" + (n?.let { " within $it candles" } ?: "")
    open fun nextConfirm(long: Boolean, price: String, n: Int?) =
        "A 15M candle must close ${if (long) "above" else "below"} $price with RSI ${if (long) "above" else "below"} 50" + (n?.let { " within $it candles" } ?: "")
