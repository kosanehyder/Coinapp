    open fun planSummary(long: Boolean, lo: String, hi: String, stop: String, tp1: String?, tp2: String?) = buildString {
        append("${direction(long)} setup confirmed. Consider entry only between $lo and $hi. ")
        append(if (long) "If price is above this range, do not chase. " else "If price is below this range, do not chase. ")
        append("Stop is $stop.")
        if (tp1 != null) append(" First target $tp1")
        if (tp2 != null) append(", second target $tp2")
        append(". This is analysis; the app does not place orders.")
    }
